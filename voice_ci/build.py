"""Build an EVA domain from a voice-ci agent profile and its caller suite.

Writes into the EVA checkout (.eva/):
  configs/agents/<domain>_agent.yaml        agent + tool schemas (taken from the live session)
  configs/prompts/zz_voice_ci_<domain>.yaml caller (user simulator) prompt for the domain
  data/<domain>_dataset.json                one EVA record per caller
  data/<domain>_scenarios/<id>.json         empty starting database per caller
  src/eva/assistant/tools/<domain>_tools.py outcome tool shim (runs the agent's outcome command)

Usage: python build.py <agent_dir> <eva_dir>
"""

import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).parent

COMMON_EDGES = [
    "Only give your name, city or address when the agent asks for them.",
    "If the agent asks anything else you do not have an answer for, say you are not sure.",
    "Never invent new goals, requests, or problems beyond what is defined here.",
]
NO_TRANSFER = "Do not ask for a person or a manager. If offered a transfer, decline."


def _param(name: str, schema: dict) -> dict:
    t = schema.get("type", "string")
    if isinstance(t, list):
        t = next((x for x in t if x != "null"), "string")
    p = {"name": name, "type": t, "description": schema.get("description", "")}
    if "enum" in schema:
        p["enum"] = [e for e in schema["enum"] if e is not None]
    return p


def _tools_from_session(session: dict) -> list[dict]:
    raw = list(session.get("tools") or [])
    deleg = (session.get("delegation") or {}).get("responses") or {}
    raw += deleg.get("tools") or []
    tools = []
    for t in raw:
        if t.get("type") != "function":
            continue
        params = (t.get("parameters") or {}).get("properties") or {}
        required = set((t.get("parameters") or {}).get("required") or [])
        tools.append({
            "id": t["name"],
            "name": t["name"],
            "description": t.get("description", ""),
            "tool_type": "write",
            "domain": "calls",
            "required_parameters": [_param(k, v) for k, v in params.items() if k in required],
            "optional_parameters": [_param(k, v) for k, v in params.items() if k not in required],
        })
    return tools


def _record(c: dict, suite: dict) -> dict:
    first, _, last = c["name"].partition(" ")
    date = suite["date"]
    expected = {"_current_date": date.split(" ")[0], "calls": {"1": c["expected"]} if c.get("expected") else {}}
    personas = suite.get("personas", {})
    return {
        "id": c["id"],
        "current_date_time": date,
        "category": suite.get("category", "voice-ci"),
        "user_goal": {
            "high_level_user_goal": c["goal"],
            "decision_tree": {
                "must_have_criteria": c.get("must", []),
                "nice_to_have_criteria": c.get("nice", []),
                "negotiation_behavior": c.get("behavior", []),
                "resolution_condition": c["resolution"],
                "failure_condition": c["failure"],
                "escalation_behavior": c.get("escalation", suite.get("escalation", NO_TRANSFER)),
                "edge_cases": list(c.get("edges", [])) + list(suite.get("edges", COMMON_EDGES)),
            },
            "information_required": c.get("info", {}),
        },
        "user_config": {
            "name": c["name"],
            "gender": c.get("gender", "woman"),
            "user_persona_id": 1,
            "user_persona": personas.get(c.get("persona"), c.get("persona", "")),
        },
        "expected_flow": c.get("flow", ""),
        "scenario_context": {"premise": c.get("premise", ""), "user_priorities": []},
        "ground_truth": {"expected_scenario_db": expected},
        "starting_utterances": {"en": c["opener"]},
        "culture_overrides": {"en": {"first_name": first, "last_name": last, "phone": suite.get("caller_number", "")}},
        "romanized_culture_overrides": {"en": {"first_name": first, "last_name": last}},
    }


SHIM = '''"""Generated by voice-ci build. Runs the agent's outcome command for every tool call."""
import json
import os
import subprocess


def _run(name, params, db, call_index):
    r = subprocess.run(
        os.environ["VOICE_CI_OUTCOME_CMD"], shell=True, cwd=os.environ.get("VOICE_CI_AGENT_DIR"),
        input=json.dumps({{"tool": name, "args": params}}), capture_output=True, text=True, timeout=30,
    )
    if r.returncode != 0:
        return {{"status": "error", "message": r.stderr[-400:]}}
    out = json.loads(r.stdout or "{{}}")
    if out.get("record") is not None:
        db.setdefault("calls", {{}})[str(call_index)] = out["record"]
    return {{"status": "success", "kind": out.get("kind"), **(out.get("result") or {{}})}}

{funcs}'''


def main(agent_dir: Path, eva: Path) -> None:
    prof = yaml.safe_load((agent_dir / "agent.yaml").read_text())
    domain = prof["domain"]
    suite = yaml.safe_load((agent_dir / prof.get("suite", "suite.yaml")).read_text())
    live = json.loads((agent_dir / prof.get("live_config", "live.json")).read_text())
    session = live["session"]
    tools = _tools_from_session(session)
    deleg = ((session.get("delegation") or {}).get("responses") or {}).get("instructions", "")

    agent = {
        "id": f"agent_{domain}",
        "name": prof.get("name", domain),
        "description": prof.get("description", f"Voice agent under test ({domain})."),
        "role": prof.get("role", f"You are {prof.get('name', 'the assistant')}."),
        "tool_module_path": f"eva.assistant.tools.{domain}_tools",
        "instructions": session.get("instructions", "") + ("\n\nBackend instructions:\n" + deleg if deleg else ""),
        "tools": tools,
    }
    (eva / f"configs/agents/{domain}_agent.yaml").write_text(yaml.safe_dump(agent, sort_keys=False, allow_unicode=True))

    caller = (HERE / "caller_prompt.txt").read_text().replace("__BUSINESS__", suite.get("business", prof.get("business", "a business")))
    (eva / f"configs/prompts/zz_voice_ci_{domain}.yaml").write_text(
        yaml.safe_dump({"user_simulator": {f"system_prompt_{domain}": caller}}, sort_keys=False, allow_unicode=True, width=10_000))

    records = [_record(c, suite) for c in suite["callers"]]
    (eva / f"data/{domain}_dataset.json").write_text(json.dumps(records, indent=2) + "\n")
    scen = eva / f"data/{domain}_scenarios"
    scen.mkdir(parents=True, exist_ok=True)
    for r in records:
        (scen / f"{r['id']}.json").write_text(json.dumps({"_current_date": suite["date"].split(" ")[0], "calls": {}}, indent=2) + "\n")

    funcs = "\n".join(f"def {t['name']}(params, db, call_index):\n    return _run({t['name']!r}, params, db, call_index)\n\n" for t in tools)
    (eva / f"src/eva/assistant/tools/{domain}_tools.py").write_text(SHIM.format(funcs=funcs))
    print(f"built domain {domain}: {len(records)} callers, tools {[t['name'] for t in tools]}")


if __name__ == "__main__":
    main(Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve())
